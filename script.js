function setLanguage(language) {
  const selected = copy[language] ? language : "en";
  document.documentElement.dataset.language = selected;
  document.documentElement.lang = selected;
  document.querySelectorAll("[data-copy]").forEach((element) => {
    const value = copy[selected][element.dataset.copy];
    if (value) element.textContent = value;
  });
  document.querySelectorAll("[data-language-button]").forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.languageButton === selected));
  });
  localStorage.setItem("lasthit-language", selected);
}

document.querySelectorAll("[data-language-button]").forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.languageButton));
});

const savedLanguage = localStorage.getItem("lasthit-language");
const browserLanguage = navigator.language.toLowerCase().startsWith("fr") ? "fr" : "en";
setLanguage(savedLanguage || browserLanguage);
